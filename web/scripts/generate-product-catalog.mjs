// Reads the product's own frontend sources and writes the page/setting catalog
// both the renderer and the engine compile against. Nothing here is a list of
// pages someone maintains by hand: a page exists because the Page union says so,
// a setting exists because the settings nav ships it, a media action exists
// because the Bridge contract declares it. Run with --check to fail on drift
// instead of rewriting, which is what CI does.
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, rename, unlink, writeFile } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'
import { dirname, relative, resolve, sep } from 'node:path'

const check = process.argv.includes('--check')
const root = resolve(import.meta.dirname, '..', '..')
const web = resolve(root, 'web')
// Sources are checked out with CRLF on Windows; every pattern below is written
// against LF so the parse cannot depend on the developer's platform.
const read = async target => (await readFile(resolve(web, target), 'utf8')).replace(/\r\n/g, '\n')
const quoted = src => [...src.matchAll(/'([^']+)'/g)].map(hit => hit[1])

const appTypes = await read('src/app/appTypes.ts')
const pageUnion = appTypes.match(/export type Page=((?:'[^']+'\|?)+)/)?.[1]
if (!pageUnion) throw new Error('Could not parse the Page union from src/app/appTypes.ts')
const pageIDs = quoted(pageUnion)
if (pageIDs.length < 10) throw new Error(`Page union parsed as too small: ${pageIDs.join(',')}`)

// PAGE_ATLAS is the product's page dictionary and is type-checked as
// Record<Page, PageSpec>, so it cannot fall behind the union. The engine reads
// the same names and domains from here rather than keeping a second copy: the
// stable key of a page card is feature.<domain>.page.<id>, so a domain that
// disagreed across the two languages would silently produce cards the frontend
// can never match to a page.
const atlas = await read('src/productHub/hubCatalog.ts')
const pageMeta = new Map(
  [...atlas.matchAll(/^\s*id: '([^']+)', name: '([^']+)', nameEn: '([^']+)', domain: '([^']+)', module: '([^']+)',$/gm)]
    .map(hit => [hit[1], { id: hit[1], name: hit[2], nameEn: hit[3], domain: hit[4], module: hit[5] }]),
)
const pages = pageIDs.map(id => {
  const meta = pageMeta.get(id)
  if (!meta) throw new Error(`PAGE_ATLAS has no entry for page '${id}'. Add it to src/productHub/hubCatalog.ts.`)
  return meta
})

const settingsSrc = await read('src/settings/settingsNav.ts')
const categoryUnion = settingsSrc.match(/export type SettingsCategory =\n((?:\s*\|\s*'[^']+'\n)+)/)?.[1]
if (!categoryUnion) throw new Error('Could not parse the SettingsCategory union from src/settings/settingsNav.ts')
const categoryIDs = quoted(categoryUnion)
const settings = [...settingsSrc.matchAll(/\{\s*id:\s*'([^']+)',\s*icon:\s*'[^']*',\s*label:\s*'([^']+)',\s*labelEn:\s*'([^']+)'/g)]
  .map(hit => ({ id: hit[1], label: hit[2], labelEn: hit[3] }))
// A category in the union with no nav row is a settings page the user can never
// open; a nav row outside the union would not compile. Comparing the two is what
// replaces a hand-updated expected count here.
const missingNav = categoryIDs.filter(id => !settings.some(item => item.id === id))
if (missingNav.length) throw new Error(`SettingsCategory declares ${missingNav.join(', ')} with no SETTINGS_CATEGORIES row`)
if (settings.length !== categoryIDs.length) throw new Error(`Parsed ${settings.length} settings rows for ${categoryIDs.length} categories`)

const officeSrc = await read('src/settings/officeMenuSettings.ts')
const officeType = officeSrc.match(/export type OfficeMenuSettings = \{([^}]+)\}/s)?.[1] ?? ''
const officeMenu = [...officeType.matchAll(/^\s*([a-zA-Z]+):\s*boolean/gm)].map(hit => hit[1])
if (officeMenu.length < 6) throw new Error(`Office menu keys parsed as too few: ${officeMenu.join(',')}`)
const strayOffice = officeMenu.filter(id => !pageIDs.includes(id))
if (strayOffice.length) throw new Error(`Office menu toggles ${strayOffice.join(', ')} which are not pages`)

// The Bridge contract owns the media vocabulary. Copying it here by hand is how
// a new transport action ends up with no card in the hub.
const bridgeSrc = await read('src/generated/bridge.ts')
const mediaDTO = bridgeSrc.match(/export type MediaOperationDTO = \{(.+?)\}\n/s)?.[1]
const mediaUnion = mediaDTO?.match(/"action":\s*([^;]+);/)?.[1]
if (!mediaUnion) throw new Error('Could not parse MediaOperationDTO.action from src/generated/bridge.ts')
const mediaActions = [...mediaUnion.matchAll(/"([a-z_]+)"/g)].map(hit => hit[1])
if (mediaActions.length < 8) throw new Error(`Media actions parsed as too few: ${mediaActions.join(',')}`)

const ts = `/* Generated by web/scripts/generate-product-catalog.mjs — do not edit. */
import type { Page } from '../app/appTypes'
import type { SettingsCategory } from '../settings/settingsNav'

export const CATALOG_PAGES = [
${pages.map(page => `  '${page.id}',`).join('\n')}
] as const satisfies readonly Page[]

export const CATALOG_SETTINGS = [
${settings.map(item => `  { id: '${item.id}', label: '${item.label}', labelEn: '${item.labelEn}' },`).join('\n')}
] as const satisfies readonly Readonly<{ id: SettingsCategory; label: string; labelEn: string }>[]

export const CATALOG_OFFICE_MENU = [
${officeMenu.map(id => `  '${id}',`).join('\n')}
] as const satisfies readonly Page[]

export const CATALOG_MEDIA_ACTIONS = [
${mediaActions.map(id => `  '${id}',`).join('\n')}
] as const
`

const go = `// Code generated by web/scripts/generate-product-catalog.mjs. DO NOT EDIT.

package generated

// Page is one reachable frontend page, carrying the name and domain the hub
// builds its stable keys from.
type Page struct {
ID string
Name string
NameEN string
Domain string
Module string
}

type Setting struct {
ID string
Name string
NameEN string
}

var Pages = []Page{
${pages.map(p => `{ID: "${p.id}", Name: "${p.name}", NameEN: "${p.nameEn}", Domain: "${p.domain}", Module: "${p.module}"},`).join('\n')}
}

var Settings = []Setting{
${settings.map(item => `{ID: "${item.id}", Name: "${item.label}", NameEN: "${item.labelEn}"},`).join('\n')}
}

var OfficeMenu = []string{
${officeMenu.map(id => `"${id}",`).join('\n')}
}

var MediaActions = []string{
${mediaActions.map(id => `"${id}",`).join('\n')}
}
`

const outputs = new Map([
  [resolve(web, 'src/generated/productCatalog.ts'), ts],
  [resolve(root, 'internal/producthub/generated/catalog.go'), execFileSync('gofmt', [], { input: go, encoding: 'utf8' })],
])
let drift = false
for (const [target, content] of outputs) {
  let current
  try { current = await readFile(target, 'utf8') } catch (error) { if (error.code !== 'ENOENT') throw error }
  if (current === content) continue
  if (check) {
    console.error(`Generated product catalog is stale: ${relative(root, target).split(sep).join('/')}`)
    drift = true
    continue
  }
  // Publish whole files: a crash mid-write must not leave TypeScript or the Go
  // build reading half a catalog.
  await mkdir(dirname(target), { recursive: true })
  const temporary = `${target}.${randomUUID()}.tmp`
  try {
    await writeFile(temporary, content, { encoding: 'utf8', flag: 'wx' })
    await rename(temporary, target)
  } finally {
    await unlink(temporary).catch(error => { if (error.code !== 'ENOENT') throw error })
  }
}
if (drift) process.exitCode = 1
else if (!check) console.log(`product catalog: ${pages.length} pages, ${settings.length} settings, ${officeMenu.length} office keys, ${mediaActions.length} media actions`)
